/* Packs stroke data for the characters used in the game into js/hanzi-data.js.
 * usage: node tools/build_hanzi.js /path/to/hanzi-writer-data/data
 * Data: Make Me a Hanzi (Arphic Public License), via the hanzi-writer-data package.
 */
'use strict';
var fs = require('fs'), path = require('path');
require('../src/js/data.js'); require('../src/js/phrases.js'); require('../src/js/phrases2.js');
var MD = globalThis.MD, dir = process.argv[2];
var chars = {};
MD.PHRASES.forEach(function (p) { Array.from(p.hz).forEach(function (c) { chars[c] = 1; }); });
MD.CHARS.forEach(function (c) { chars[c.ch] = 1; });
var out = {}, missing = [];
Object.keys(chars).forEach(function (c) {
  var f = path.join(dir, c + '.json');
  if (!fs.existsSync(f)) { missing.push(c); return; }
  var d = JSON.parse(fs.readFileSync(f, 'utf8'));
  // glyph box is 1024 wide with y pointing up from a baseline at -124: grid = ((x), (900 - y)) * 100 / 1024
  out[c] = {
    s: d.strokes,
    m: d.medians.map(function (m) { return m.map(function (p) { return [Math.round(p[0] * 1000 / 1024) / 10, Math.round((900 - p[1]) * 1000 / 1024) / 10]; }); })
  };
});
if (missing.length) { console.error('MISSING:', missing.join('')); process.exit(1); }
var js = '/* Stroke outlines and centre lines. Source: Make Me a Hanzi (Arphic Public License). Generated by tools/build_hanzi.js */\n' +
  '(function (r) { var MD = r.MD = r.MD || {}; MD.HZ = ' + JSON.stringify(out) + '; })(typeof window !== "undefined" ? window : globalThis);\n';
fs.writeFileSync(path.join(__dirname, '..', 'src', 'js', 'hanzi-data.js'), js);
console.log('characters:', Object.keys(out).length, 'bytes:', js.length);
